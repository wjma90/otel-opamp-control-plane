export function normalizeLocale(value) {
  const normalized = String(value || "").trim().toLowerCase().split(/[-_]/)[0];
  return supportedLocales.includes(normalized) ? normalized : defaultLocale;
}

export function translate(locale, message, variables = {}) {
  const source = String(message ?? "");
  let template = source;
  if (normalizeLocale(locale) === "en") {
    template = english[source] || source;
    if (template === source) {
      const match = englishPatterns.find(([pattern]) => pattern.test(source));
      if (match) template = source.replace(match[0], match[1]);
    }
  }
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key) =>
    Object.prototype.hasOwnProperty.call(variables, key) ? String(variables[key]) : match,
  );
}

export function formatDateTime(locale, value) {
  const date = value instanceof Date ? value : new Date(value);
  if (Number.isNaN(date.getTime())) return "—";
  return new Intl.DateTimeFormat(normalizeLocale(locale) === "en" ? "en-US" : "es-PE", {
    dateStyle: "short",
    timeStyle: "medium",
  }).format(date);
}

export function readStoredLocale(storage = globalThis.localStorage) {
  try {
    return normalizeLocale(storage?.getItem(localeStorageKey));
  } catch {
    return defaultLocale;
  }
}

const I18nContext = createContext({
  locale: defaultLocale,
  setLocale: () => {},
  t: (message, variables) => translate(defaultLocale, message, variables),
  formatDate: (value) => formatDateTime(defaultLocale, value),
});

export function I18nProvider({ children, storage = globalThis.localStorage }) {
  const [locale, setLocale] = useState(() => readStoredLocale(storage));

  useEffect(() => {
    document.documentElement.lang = locale;
    try {
      storage?.setItem(localeStorageKey, locale);
    } catch {
      // Storage can be unavailable in hardened/private browser contexts.
    }
  }, [locale, storage]);

  const value = useMemo(() => ({
    locale,
    setLocale: (nextLocale) => setLocale(normalizeLocale(nextLocale)),
    t: (message, variables) => translate(locale, message, variables),
    formatDate: (date) => formatDateTime(locale, date),
  }), [locale]);

  return React.createElement(I18nContext.Provider, { value }, children);
}

export function useI18n() {
  return useContext(I18nContext);
}

export function translatedOptions(t, options) {
  return (options || []).map((option) => ({ ...option, label: t(option.label) }));
}

